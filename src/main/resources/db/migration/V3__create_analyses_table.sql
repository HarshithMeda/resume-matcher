-- Results of matching a resume against a job description.
-- The job description text itself is NOT stored; only the computed result (JSON).
-- Deleting a resume (or user) deletes its analyses, since they describe that resume.
CREATE TABLE analyses (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    resume_id   BIGINT      NOT NULL REFERENCES resumes (id) ON DELETE CASCADE,
    match_score INTEGER     NOT NULL CHECK (match_score BETWEEN 0 AND 100),
    result      JSONB       NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_analyses_user_id_created_at ON analyses (user_id, created_at DESC);
-- Speeds up the cascade when a resume is deleted.
CREATE INDEX idx_analyses_resume_id ON analyses (resume_id);
