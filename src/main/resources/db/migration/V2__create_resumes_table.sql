-- Only the extracted text and the file name are stored, never the original PDF.
CREATE TABLE resumes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    file_name      VARCHAR(255) NOT NULL,
    extracted_text TEXT         NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Every query filters by owner; this also serves "newest first" listing.
CREATE INDEX idx_resumes_user_id_created_at ON resumes (user_id, created_at DESC);
